import { NotebookCell, PipelineConfig } from '../types/studio';

export function exportPipelineToIpynb(
  projectName: string,
  config: PipelineConfig,
  cells: NotebookCell[]
): void {
  const ipynbCells: Record<string, unknown>[] = [
    {
      cell_type: 'markdown',
      metadata: {},
      source: [
        `# ${projectName}\n`,
        `Generated by **AMLICS (AutoML & Interactive Code Studio)**\n`,
        `- **Task:** \`${config.taskType}\` | **Target:** \`${config.targetColumn}\`\n`,
        `- **Estimator:** \`${config.modelFamily}\` | **Validation:** \`${config.cvStrategy} (${config.cvFolds} folds)\`\n`,
      ],
    },
  ];

  for (const cell of cells) {
    if (cell.cellType === 'markdown') {
      ipynbCells.push({
        cell_type: 'markdown',
        metadata: {
          id: cell.id,
          title: cell.title,
        },
        source: cell.currentCode
          .split('\n')
          .map((line, i, arr) => (i < arr.length - 1 ? line + '\n' : line)),
      });
      continue;
    }

    const outputs: Record<string, unknown>[] = [];
    if (cell.outputText && cell.outputText.trim()) {
      outputs.push({
        output_type: 'stream',
        name: 'stdout',
        text: cell.outputText.split('\n').map((line) => line + '\n'),
      });
    }

    if (cell.figures && cell.figures.length > 0) {
      for (const figB64 of cell.figures) {
        const cleanB64 = figB64.replace(/^data:image\/png;base64,/, '');
        outputs.push({
          output_type: 'display_data',
          data: {
            'image/png': cleanB64,
            'text/plain': ['<Figure>'],
          },
          metadata: {},
        });
      }
    }

    ipynbCells.push({
      cell_type: 'code',
      execution_count: cell.status === 'success' ? cell.order : null,
      metadata: {
        id: cell.id,
        automl_step: cell.stepType,
        title: cell.title,
        is_locked: cell.isLocked,
      },
      source: cell.currentCode
        .split('\n')
        .map((line, i, arr) => (i < arr.length - 1 ? line + '\n' : line)),
      outputs,
    });
  }

  const notebookObj = {
    nbformat: 4,
    nbformat_minor: 5,
    metadata: {
      kernelspec: {
        display_name: 'Python 3 (ipykernel)',
        language: 'python',
        name: 'python3',
      },
      language_info: {
        name: 'python',
        version: '3.11.0',
      },
    },
    cells: ipynbCells,
  };

  const blob = new Blob([JSON.stringify(notebookObj, null, 2)], {
    type: 'application/x-ipynb+json',
  });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  const safeTitle = projectName.toLowerCase().replace(/[^a-z0-9]+/g, '_');
  a.href = url;
  a.download = `${safeTitle}.ipynb`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function parseImportedIpynb(jsonContent: string): NotebookCell[] {
  const parsed = JSON.parse(jsonContent);
  const rawCells: Record<string, unknown>[] = Array.isArray(parsed.cells)
    ? parsed.cells
    : [];

  const result: NotebookCell[] = [];
  let orderCounter = 1;

  for (const rc of rawCells) {
    const cType = rc.cell_type === 'markdown' ? 'markdown' : 'code';
    const rawSource = rc.source;
    const sourceText = Array.isArray(rawSource)
      ? rawSource.join('')
      : typeof rawSource === 'string'
      ? rawSource
      : '';

    if (!sourceText.trim() && cType === 'markdown') continue;

    const meta = (rc.metadata || {}) as Record<string, unknown>;
    const stepType =
      typeof meta.automl_step === 'string'
        ? (meta.automl_step as NotebookCell['stepType'])
        : cType === 'markdown'
        ? 'markdown_doc'
        : 'custom';

    let outputText = '';
    const figures: string[] = [];

    if (Array.isArray(rc.outputs)) {
      for (const out of rc.outputs as Record<string, unknown>[]) {
        if (out.output_type === 'stream' && out.text) {
          outputText += Array.isArray(out.text)
            ? out.text.join('')
            : String(out.text);
        } else if (
          (out.output_type === 'display_data' ||
            out.output_type === 'execute_result') &&
          out.data
        ) {
          const dataObj = out.data as Record<string, unknown>;
          if (typeof dataObj['image/png'] === 'string') {
            const b64 = dataObj['image/png'].replace(/\n/g, '');
            figures.push(
              b64.startsWith('data:image')
                ? b64
                : `data:image/png;base64,${b64}`
            );
          } else if (dataObj['text/plain']) {
            const txt = Array.isArray(dataObj['text/plain'])
              ? dataObj['text/plain'].join('')
              : String(dataObj['text/plain']);
            if (!txt.startsWith('<Figure')) {
              outputText += txt + '\n';
            }
          }
        }
      }
    }

    const firstLine = sourceText
      .split('\n')[0]
      ?.replace(/^[#\s]+/, '')
      .slice(0, 48);

    result.push({
      id:
        typeof meta.id === 'string'
          ? meta.id
          : `imported_${Date.now()}_${orderCounter}`,
      order: orderCounter,
      cellType: cType,
      stepType,
      title:
        typeof meta.title === 'string'
          ? meta.title
          : cType === 'markdown'
          ? firstLine || `Markdown Note #${orderCounter}`
          : firstLine || `Code Cell #${orderCounter}`,
      subtitle:
        cType === 'markdown'
          ? 'Markdown documentation'
          : stepType === 'custom'
          ? 'Imported code cell (Locked)'
          : 'Synced pipeline step',
      generatedCode: sourceText,
      currentCode: sourceText,
      isLocked: stepType === 'custom' ? true : Boolean(meta.is_locked ?? true),
      status: outputText || figures.length > 0 ? 'success' : 'idle',
      outputText: outputText.trim(),
      figures,
    });

    orderCounter++;
  }

  return result;
}

export function downloadCloudRunnerIpynb(
  sessionId: string,
  supabaseUrl: string,
  supabaseAnonKey: string
): void {
  const script = generateOneClickColabScript(sessionId, supabaseUrl, supabaseAnonKey);
  const notebookObj = {
    nbformat: 4,
    nbformat_minor: 5,
    metadata: {
      colab: {
        provenance: [],
        gpuType: 'T4',
      },
      accelerator: 'GPU',
      kernelspec: {
        display_name: 'Python 3',
        name: 'python3',
      },
    },
    cells: [
      {
        cell_type: 'markdown',
        metadata: {},
        source: [
          '# AMLICS — Remote Cloud Worker (Google Colab / Kaggle)\n',
          'Run the cell below once. When `CONNECTED TO AMLICS WEB STUDIO!` appears, minimize this tab and control execution from the AMLICS web app.\n',
        ],
      },
      {
        cell_type: 'code',
        execution_count: null,
        metadata: {},
        outputs: [],
        source: script.split('\n').map((l, i, arr) => (i < arr.length - 1 ? l + '\n' : l)),
      },
    ],
  };

  const blob = new Blob([JSON.stringify(notebookObj, null, 2)], {
    type: 'application/x-ipynb+json',
  });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `AMLICS_Cloud_Worker_${sessionId.slice(0, 8)}.ipynb`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
